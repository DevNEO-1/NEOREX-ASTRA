import { ChatRequestPayload, ChatSuccessResponse } from './types.js';

/**
 * Safe, scientifically audited fallback when network or API key is unavailable.
 * Guarantees 100% uptime for students without crashing.
 * Acknowledges the question and provides authentic educational science guidance.
 */
export function generateDeterministicFallback(payload: ChatRequestPayload): ChatSuccessResponse {
  const { learningProfile, simulationContext, message } = payload;
  const lower = message.trim().toLowerCase();

  let advice = '';

  // 1. Greetings
  if (/^(hi|hello|hey|howdy|greetings|good morning|good afternoon|good evening)\b/i.test(lower)) {
    if (learningProfile === 'junior') {
      advice = `Hello Astronaut! I'm Dr. Astra, your space science mentor. We are on Day ${simulationContext.day} of our mission. What would you like to explore today? 🚀`;
    } else if (learningProfile === 'cadet') {
      advice = `Greetings Cadet! Dr. Astra reporting for Day ${simulationContext.day} operations. Life support, power, and habitats are operational. Ask me anything about space physics or mission engineering.`;
    } else {
      advice = `Commander, Dr. Astra online. Telemetry is synchronized for Day ${simulationContext.day}. Subsystems are nominal. Ready to assist with ECLSS analysis, power trade-offs, or orbital logistics.`;
    }
  }
  // 2. Fundamental Space Questions
  else if (lower.includes('what is space') || lower.includes('about space') || lower.includes('outer space') || lower.includes('universe')) {
    if (learningProfile === 'junior') {
      advice = `Space is the huge, wonderful place beyond Earth's sky! It has no air to breathe, so astronauts wear special spacesuits with oxygen tanks and helmets. It's filled with stars, planets, and moons waiting to be explored! 🌟`;
    } else if (learningProfile === 'cadet') {
      advice = `Outer space is a near-perfect vacuum that begins above Earth's atmosphere (the Kármán line at 100 km). Without atmospheric pressure or air, space explorers must bring closed-loop life support (oxygen, water, temperature regulation) and radiation shielding.`;
    } else {
      advice = `Outer space is an ultra-high vacuum environment characterized by microgravity, zero atmospheric pressure (< 10⁻¹⁴ Pa), extreme diurnal temperature deltas, and omnidirectional ionizing radiation (solar proton events and galactic cosmic rays). Human spaceflight requires sealed pressurized habitats and regenerative life support.`;
    }
  }
  // 3. Oxygen
  else if (lower.includes('oxygen') || lower.includes('air') || lower.includes('breathe') || lower.includes('o2')) {
    if (learningProfile === 'junior') {
      advice = `Astronauts need oxygen to breathe! Our base makes fresh oxygen using clean water and electricity. Keep your water tanks filled and your oxygen generators running! 🌬️`;
    } else if (learningProfile === 'cadet') {
      advice = `Oxygen is generated by water electrolysis (splitting H2O into O2 and H2). 4 astronauts consume ~3.2 kg O2/day. Check that electrolysis is active and water is flowing to maintain your breathable atmosphere.`;
    } else {
      advice = `Stoichiometric O2 generation: Baseline human consumption is 0.84 kg O2/person/day (3.2 kg/day for 4 crew). Electrolysis requires 3.6 L/day H2O and 19.2 kWh/day electrical cell load to balance cabin partial pressure.`;
    }
  }
  // 4. Water
  else if (lower.includes('water') || lower.includes('thirst') || lower.includes('recycle') || lower.includes('h2o')) {
    if (learningProfile === 'junior') {
      advice = `Water is super precious! Our recycler cleans water from astronaut breath and sweat so we can drink it again. Make sure our water tanks don't run empty! 💧`;
    } else if (learningProfile === 'cadet') {
      advice = `On the Moon, water cannot be replenished easily from Earth. In our simulation, baseline recycling starts at 80%, but NASA's real ISS system recovers 98% of wastewater. Upgrading our recycler above 85% prevents rapid depletion.`;
    } else {
      advice = `Closed-loop hydrology reference: NASA ISS Water Processor Assembly achieves ~98% recovery. In this simulation, recycling starts at 80% with upgrade paths up to 95%. Balance the 3.6 L/day electrolysis demand with your current recovery capacity.`;
    }
  }
  // 5. Power
  else if (lower.includes('power') || lower.includes('battery') || lower.includes('solar') || lower.includes('night') || lower.includes('energy')) {
    if (learningProfile === 'junior') {
      advice = `Our big solar panels catch sunlight! When it's dark night on the Moon, we rely on batteries. Turn off extra machines to save power! ⚡`;
    } else if (learningProfile === 'cadet') {
      advice = `A lunar night lasts 14 Earth days (336 hours in non-polar zones, compared to the ~14.75 day / 354 hr astronomical synodic half-period). Ensure battery reserves exceed 500 kWh before sunset and toggle non-critical systems to power-rationing mode.`;
    } else {
      advice = `In this simulation, lunar night is simplified to 14 Earth days (336 hours, vs ~14.75-day / 354-hour astronomical synodic non-polar darkness). Cryogenic night insolation is 0 W/m². Base life support requires 35.2 kWh/day minimum. Shed the 6.0 kWh/day greenhouse auxiliary load to prevent deep-cycle battery depletion.`;
    }
  }
  // 6. Radiation
  else if (lower.includes('radiation') || lower.includes('storm') || lower.includes('shield') || lower.includes('cosmic')) {
    if (learningProfile === 'junior') {
      advice = `Cosmic rays are invisible space particles! We pile thick moon dirt on top of our habitat to keep our astronaut crew safe inside! 🛡️`;
    } else if (learningProfile === 'cadet') {
      advice = `Galactic cosmic rays and solar flares deliver ionizing radiation. Artemis I measured deep-space GCR doses of 0.96-1.24 mSv/day inside Orion during cis-lunar transit; our lunar outpost simulation uses 1.00 mSv/day unshielded as an educational game assumption. Regolith shielding safely blocks high-energy ions!`;
    } else {
      advice = `Radiation reference: NASA Artemis I Orion measured 0.96-1.24 mSv/day inside the capsule during cis-lunar transit; our lunar surface outpost models unshielded radiation as an assumed 1.00 mSv/day scenario (with the lunar body providing a 2-pi planetary shadow). Passive regolith mass attenuation reduces dose equivalent towards terrestrial occupational limits.`;
    }
  }
  // 7. General / Unknown questions
  else {
    const cleanQuestion = message.length > 80 ? `${message.substring(0, 77)}...` : message;
    if (learningProfile === 'junior') {
      advice = `You asked: "${cleanQuestion}". That's a great space question! Here on our Moon base, our astronauts are learning how to build a real colony by managing oxygen, fresh water, and solar power. Keep exploring! 🚀`;
    } else if (learningProfile === 'cadet') {
      advice = `Regarding your inquiry: "${cleanQuestion}" — Space exploration requires balancing physics and engineering. On Day ${simulationContext.day}, monitor your ECLSS life-support gauges and ask about life support, solar energy, water recycling, or radiation shielding.`;
    } else {
      advice = `Technical query recorded: "${cleanQuestion}". ECLSS and telemetry indicate nominal conditions on Day ${simulationContext.day}. For mission engineering guidance, query life-support stoichiometry, power load-shedding, or radiation mitigation.`;
    }
  }

  return {
    success: true,
    response: advice,
    ageTier: learningProfile,
    timestamp: new Date().toISOString(),
    isFallback: true,
  };
}
